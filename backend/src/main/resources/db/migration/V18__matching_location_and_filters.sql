ALTER TABLE company_profiles
    -- Where the company is based (NUTS 3 subregion, e.g. PL214 Krakowski) – the centre of the working radius.
    ADD COLUMN base_nuts varchar(5) REFERENCES nuts_regions (code),
    -- Works and on-site services within this distance from the base; NULL = no distance limit.
    ADD COLUMN max_distance_km int CHECK (max_distance_km BETWEEN 10 AND 2000),
    -- PREFER: farther tenders score lower; STRICT: tenders outside the area are not matched at all.
    ADD COLUMN region_mode text NOT NULL DEFAULT 'PREFER' CHECK (region_mode IN ('PREFER', 'STRICT')),
    -- Additional regions (any NUTS level, e.g. a whole voivodeship PL22) where the company also works.
    ADD COLUMN extra_regions varchar(5)[] NOT NULL DEFAULT '{}',
    -- Supplies are usually delivered anywhere in the country: the radius then does not apply to them.
    ADD COLUMN supplies_nationwide boolean NOT NULL DEFAULT true,
    ADD COLUMN include_keywords text[] NOT NULL DEFAULT '{}',
    ADD COLUMN exclude_keywords text[] NOT NULL DEFAULT '{}',
    -- CPV codes (prefixes) the company never does, even inside its sectors (e.g. 45221 bridges).
    ADD COLUMN excluded_cpv varchar(8)[] NOT NULL DEFAULT '{}',
    -- Tenders closing sooner than this are left out of matches and notifications (no time to prepare).
    ADD COLUMN min_days_to_deadline int CHECK (min_days_to_deadline BETWEEN 0 AND 60);

-- "Not relevant" on a match: hidden for the organization, the reason helps to tune the profile.
CREATE TABLE match_dismissals (
    organization_id  uuid        NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
    tender_id        uuid        NOT NULL REFERENCES tenders (id) ON DELETE CASCADE,
    reason           text        NOT NULL
                     CHECK (reason IN ('LOCATION', 'SECTOR', 'VALUE', 'CONTRACT_TYPE', 'REQUIREMENTS', 'DEADLINE', 'OTHER')),
    user_id          uuid        REFERENCES users (id) ON DELETE SET NULL,
    created_at       timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, tender_id)
);
